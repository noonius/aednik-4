const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const path = require('node:path');
const study = require('./docs/study.js');
const context = { window: {} }; vm.runInNewContext(fs.readFileSync(path.join(__dirname, 'docs/taimed.js'), 'utf8'), context);
const plants = context.window.PLANTS;
assert.equal(plants.length, 419);
assert.equal(new Set(plants.map(p => p.id)).size, plants.length);
assert.equal(new Set(plants.map(p => p.group)).size, 14);
for (const p of plants) if (p.image) assert.ok(fs.existsSync(path.join(__dirname, 'docs', p.image)));
const now = 1000000000;
let state = study.schedule(null, true, now); assert.equal(state.due - now, 86400000);
state = study.schedule(state, true, now); assert.equal(state.due - now, 3 * 86400000);
state = study.schedule(state, false, now); assert.equal(state.level, 0); assert.equal(state.due - now, 600000);
for (let i = 0; i < 20; i++) state = study.schedule(state, true, now);
assert.equal(state.level, 6); assert.equal(state.due - now, 60 * 86400000);
const selected = study.select(plants, {}, 'image', 'Püsililled', now);
assert.equal(selected.length, 20); assert.ok(selected.every(p => p.image && p.group === 'Püsililled'));
const one = plants.find(p => p.latin && p.estonian); const id = study.key(one, 'et-latin');
assert.equal(study.select([one], { [id]: { due: now + 1000 } }, 'et-latin', '', now).length, 0);
assert.equal(study.select([one], { [id]: { due: now + 1000 } }, 'et-latin', '', now, true).length, 1);
assert.equal(study.select([{ id: 'missing', latin: '', estonian: 'name' }], {}, 'et-latin', '', now).length, 0);
assert.throws(() => study.validateBackup({ version: 1, progress: { [id]: { level: 90 } } }, new Set([id])));
assert.deepEqual(study.validateBackup({ version: 1, progress: { [id]: state, unknown: state } }, new Set([id])), { [id]: state });
const assets = JSON.parse(fs.readFileSync(path.join(__dirname, 'docs/offline.json')));
for (const asset of assets) if (asset !== './') assert.ok(fs.existsSync(path.join(__dirname, 'docs', asset)), asset);
console.log(`OK: ${plants.length} kirjet; rühmad, pildid, ajastamine, filtrid, õpiedu ja offline-failid kontrollitud.`);
